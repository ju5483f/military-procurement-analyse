// 檢查 0716 目標矩陣的可行性（第二階段命中數 ≤ 陸+海 案件數）
const T = {
  "1-1":  { 陸: 1, 海: 0, 空: 3, 他: 1, s2: 0 },
  "1-2":  { 陸: 7, 海: 5, 空: 10, 他: 4, s2: 5 },
  "1-3":  { 陸: 4, 海: 3, 空: 2, 他: 5, s2: 4 },
  "1-4":  { 陸: 4, 海: 2, 空: 10, 他: 0, s2: 4 },
  "1-5":  { 陸: 0, 海: 0, 空: 1, 他: 0, s2: 0 },
  "1-6":  { 陸: 0, 海: 0, 空: 0, 他: 0, s2: 0 },
  "1-7":  { 陸: 5, 海: 4, 空: 9, 他: 5, s2: 3 },
  "1-8":  { 陸: 3, 海: 1, 空: 5, 他: 0, s2: 4 },
  "1-9":  { 陸: 0, 海: 0, 空: 0, 他: 1, s2: 0 },
  "1-10": { 陸: 1, 海: 1, 空: 0, 他: 1, s2: 2 },
  "2-1":  { 陸: 8, 海: 0, 空: 0, 他: 0, s2: 5 },
  "2-2":  { 陸: 1, 海: 1, 空: 2, 他: 0, s2: 1 },
  "2-3":  { 陸: 7, 海: 2, 空: 2, 他: 2, s2: 5 },
  "2-4":  { 陸: 0, 海: 0, 空: 5, 他: 1, s2: 0 },
  "2-5":  { 陸: 1, 海: 1, 空: 5, 他: 0, s2: 1 },
  "2-6":  { 陸: 10, 海: 6, 空: 7, 他: 4, s2: 1 },
  "2-7":  { 陸: 13, 海: 1, 空: 21, 他: 1, s2: 5 },
  "2-8":  { 陸: 5, 海: 4, 空: 9, 他: 0, s2: 3 },
  "2-9":  { 陸: 2, 海: 2, 空: 19, 他: 1, s2: 2 },
  "2-10": { 陸: 9, 海: 4, 空: 2, 他: 6, s2: 10 },
};

console.log("=== 檢查一：第二階段命中數 ≤ 陸+海 案件數（會議檔只有陸軍/海軍）===");
let bad = 0;
for (const [id, t] of Object.entries(T)) {
  const lh = t.陸 + t.海;
  const ok = t.s2 <= lh;
  if (!ok) bad++;
  const tight = t.s2 === lh && lh > 0 ? "  ← 緊繃：陸海案件必須全部命中" : "";
  console.log(`  ${id.padEnd(5)} 合計${String(t.陸 + t.海 + t.空 + t.他).padStart(3)}  陸+海=${String(lh).padStart(2)}  第二階段=${String(t.s2).padStart(2)}  ${ok ? "OK" : "✗ 不可行"}${tight}`);
}
console.log(bad === 0 ? "→ 全部可行\n" : `→ ${bad} 項不可行\n`);

console.log("=== 檢查二：互斥/蘊含關係 ===");
// diff = J(1-L)。1-10 要 J>=0.9 且 L<0.5 → diff >= 0.9*0.5 = 0.45 >= 0.4 → 軍投必連帶命中 1-3
for (const svc of ["陸", "海", "空", "他"]) {
  const ok = T["1-3"][svc] >= T["1-10"][svc];
  console.log(`  ${svc}軍 1-3(${T["1-3"][svc]}) >= 1-10(${T["1-10"][svc]})  ${ok ? "OK" : "✗ 1-10 必連帶命中 1-3，數量不足"}`);
}
// 2-10 (J>=0.9,L<0.5) → diff >= 0.45，但 2-3 需 diff>=0.5 → 不必然
console.log("  註：作維 2-10 → diff>=0.45，2-3 需 diff>=0.5，故不必然連帶（有調整空間）");

console.log("\n=== 檢查三：合計是否等於四軍種和 ===");
const sums = { 軍投: 0, 作維: 0 };
for (const [id, t] of Object.entries(T)) {
  sums[id.startsWith("1-") ? "軍投" : "作維"] += t.陸 + t.海 + t.空 + t.他;
}
console.log("  軍投命中列數合計:", sums.軍投, "／作維:", sums.作維, "／總計:", sums.軍投 + sums.作維);
console.log("  （同一案件可命中多項，故此數 > 實際案件數）");
