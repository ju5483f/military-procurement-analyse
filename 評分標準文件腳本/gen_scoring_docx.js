const COLS = [900, 2200, 1300, 900, 5156];   // 合計 10456，同原檔總寬；評分標準欄加寬

const B = { style: BorderStyle.SINGLE, size: 4, color: '000000' };
const CELL_BORDERS = { top: B, bottom: B, left: B, right: B };

function p(text, opts) {
  opts = opts || {};
  return new Paragraph({
    spacing: { after: opts.after === undefined ? 0 : opts.after, line: 276 },
    indent: opts.indent ? { left: opts.indent } : undefined,
    children: [new TextRun({ text: text, size: SZ, bold: !!opts.bold })]
  });
}
function cell(text, i, opts) {
  opts = opts || {};
  return new TableCell({
    width: { size: COLS[i], type: WidthType.DXA },
    borders: CELL_BORDERS,
    verticalAlign: VerticalAlign.CENTER,
    margins: { top: 60, bottom: 60, left: 80, right: 80 },
    children: [p(text, { bold: opts.bold })]
  });
}
function table(rows) {
  return new Table({
    width: { size: 10456, type: WidthType.DXA },
    columnWidths: COLS,
    rows: rows.map(function (r, ri) {
      return new TableRow({
        tableHeader: ri === 0,
        children: r.map(function (t, ci) { return cell(t, ci, { bold: ri === 0 }); })
      });
    })
  });
}

